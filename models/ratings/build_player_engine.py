#!/usr/bin/env python3
"""Unified engine export for the dashboard (Phase A surfacing).

Denormalizes the rating/projection/duel/role outputs into ONE
player-season table so app.py needs a single cached loader instead of
six joins. Regenerated by scripts/rebuild_all.sh after the conversion
step; app code never needs to change when the engine version bumps.

Outputs:
  player_engine.parquet      one row per rated player-season
  player_engine_meta.json    {data_through, rating_version,
                              projection_version, built_at, n_rows,
                              gpa_values: per-season walk-forward provenance}

Run from the Dashboard dir: python models/ratings/build_player_engine.py
"""
from datetime import datetime
import json
from pathlib import Path

import pandas as pd

_HERE = Path(__file__).resolve().parent
_DASH = _HERE.parent.parent

print("[1/4] rating + projection…", flush=True)
r = pd.read_parquet(_HERE / 'acp_rating_per_player_season.parquet')
p = pd.read_parquet(_HERE / 'acp_projection.parquet')
proj_cols = ['playerId', 'seasonId', 'age', 'career_asof', 'age_delta',
              'w_evidence', 'projection', 'projection_abs', 'band_sd',
              'proj_delta', 'seasons_ago']
# projection covers current-season rows + lapsed (24/25, no current row);
# lapsed rows join onto their LAST rated season's rating row.
eng = r.merge(p[proj_cols], on=['playerId', 'seasonId'], how='left')

print("[2/4] teams + duel ladders + raw axis values…", flush=True)
pt = pd.read_parquet(_HERE / 'player_teams.parquet')
eng = eng.merge(pt, on=['playerId', 'seasonId'], how='left')

# raw per-axis values for the mean±2σ radar: category value/90, DefR
# volume (defr_adj), DWAE/90 (count-shrunk, same as the rating), RAPM
g = pd.read_parquet(_DASH / 'gpa_player_season_values.parquet',
                      columns=['playerId', 'seasonId', 'mins_played',
                                'Shooting', 'Receiving', 'Dribbling'])
g['playerId'] = pd.to_numeric(g['playerId'], errors='coerce').astype('Int64')
g['seasonId'] = pd.to_numeric(g['seasonId'], errors='coerce').astype('Int64')
ps = pd.read_parquet(_HERE / 'pass_split.parquet')
g = g.merge(ps.rename(columns={'Creating Value': 'Creating',
                                  'Linking Value': 'Linking'}),
              on=['playerId', 'seasonId'], how='left')
g[['Creating', 'Linking']] = g[['Creating', 'Linking']].fillna(0.0)
for c in ['Shooting', 'Creating', 'Linking', 'Receiving', 'Dribbling']:
    g[f'raw_{c}90'] = g[c] / g['mins_played'] * 90.0
eng = eng.merge(g[['playerId', 'seasonId']
                   + [f'raw_{c}90' for c in
                      ['Shooting', 'Creating', 'Linking', 'Receiving', 'Dribbling']]],
                  on=['playerId', 'seasonId'], how='left')
d = pd.read_parquet(_DASH / 'models/defr/defr_per_player_season.parquet',
                      columns=['playerId', 'seasonId', 'defr_adj',
                                'defr_dwae', 'dwae_n'])
d = d.rename(columns={'defr_adj': 'raw_resp'})
d['raw_dwae90'] = (d['defr_dwae'] * d['dwae_n'] / (d['dwae_n'] + 80.0))
eng = eng.merge(d[['playerId', 'seasonId', 'raw_resp', 'raw_dwae90', 'dwae_n']],
                  on=['playerId', 'seasonId'], how='left')
eng['raw_dwae90'] = eng['raw_dwae90'] / eng['mins_played'] * 90.0
r4 = pd.read_parquet(_HERE / 'rapm_v4_per_season.parquet')
eng = eng.merge(r4.rename(columns={'rapm_v4': 'raw_rapm'}),
                  on=['playerId', 'seasonId'], how='left')
# v7.0 NO LOOKAHEAD: the career Glicko duel ladders are no longer copied onto
# every season row (a 2021/22 row carried duels from every later season).
# The radar's Off Duel Grade raw value is the season's take-on / shield wins
# over expectation per 90 (woe_att_p90, from the rating table).

# TRUE minutes for display: every match Wyscout reports minutesOnField for,
# INCLUDING the 57 eventless Camp 25/26 matches the per-90 denominator
# (mins_played, exact API minutes over matches WITH events) leaves out.
# Exact per-match API minutes, aliases resolved (match_minutes.py) — no
# estimates and no hand-typed overrides (Lucas 2026-10-20).
import pickle
import sys as _sys
_sys.path.insert(0, str(_DASH))
from match_minutes import load_cache as _load_match_minutes  # noqa: E402
from precompute_minutes import resolve_aliases as _resolve_aliases  # noqa: E402
_mm = _load_match_minutes()
if len(_mm):
    _lm = (_resolve_aliases(_mm).groupby(['seasonId', 'playerId'], as_index=False)
           ['minutes'].sum().rename(columns={'minutes': 'mins_lineup'}))
    # Seasons with no per-match data (Campeonato, Wyscout access lost
    # 2026-10): the exact stored season totals.
    from precompute_minutes import _season_total_rows  # noqa: E402
    from match_minutes import per_match_seasons as _per_match_seasons  # noqa: E402
    _pms = _per_match_seasons(_DASH / 'match_player_minutes.parquet',
                              pd.read_parquet(_DASH / 'matches_summary.parquet', columns=['matchId', 'seasonId']))
    _lm = _lm[_lm['seasonId'].isin(_pms)]
    with open(_DASH / 'player_minutes_and_positions.pkl', 'rb') as _f:
        _api_seasons = pickle.load(_f)
    _fb = [(_season_total_rows(int(_sid), _df)[['playerId', 'totalMinutes']]
            .assign(seasonId=int(_sid)).rename(columns={'totalMinutes': 'mins_lineup'}))
           for _sid, _df in _api_seasons.items() if int(_sid) not in _pms]
    if _fb:
        _lm = pd.concat([_lm] + _fb, ignore_index=True)
    _lm['seasonId'] = _lm['seasonId'].astype('int64')
    _lm['playerId'] = _lm['playerId'].astype('int64')
    eng = eng.merge(_lm, on=['playerId', 'seasonId'], how='left')
    eng['mins_lineup'] = eng['mins_lineup'].fillna(eng['mins_played'])
else:
    eng['mins_lineup'] = eng['mins_played']

print("[3/4] data-through stamp…", flush=True)
# latest match date actually inside the engine = matches with lineup
# intervals (the rating's minute source)
iv = pd.read_parquet(_HERE / 'player_match_intervals.parquet',
                       columns=['matchId'])
ms = pd.read_parquet(_DASH / 'matches_summary.parquet',
                       columns=['matchId', 'dateutc'])
dates = pd.to_datetime(
    ms[ms['matchId'].isin(iv['matchId'].unique())]['dateutc'],
    errors='coerce')
data_through = str(dates.max().date())

print("[4/4] write…", flush=True)
eng.to_parquet(_HERE / 'player_engine.parquet')
meta = {
    'data_through': data_through,
    'rating_version': str(r['rating_version'].iloc[0]),
    'projection_version': str(p['projection_version'].iloc[0]),
    'built_at': datetime.now().strftime('%Y-%m-%d %H:%M'),
    'n_rows': int(len(eng)),
}
# v7.0: which GPA models valued each season (walk-forward provenance —
# every season's training seasons are earlier than the season itself)
_wf_manifest = _DASH.parent.parent / 'GPA Model Project v2' / 'models' / 'walkforward' / 'manifest.json'
if _wf_manifest.exists():
    meta['gpa_values'] = {
        sid: {'trained_on': e.get('trained_on'), 'frozen': bool(e.get('frozen', False))}
        for sid, e in json.loads(_wf_manifest.read_text()).get('seasons', {}).items()}
(_HERE / 'player_engine_meta.json').write_text(json.dumps(meta, indent=2))
print(f"  player_engine.parquet: {len(eng):,} rows x {len(eng.columns)} cols")
print(f"  meta: {meta}")
